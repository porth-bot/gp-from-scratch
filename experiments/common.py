"""Shared plotting setup and results logging for the experiment scripts."""

import json
import os

import matplotlib
import numpy as np

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

plt.rcParams.update(
    {
        "figure.dpi": 150,
        "savefig.dpi": 150,
        "font.size": 9,
        "axes.titlesize": 10,
        "axes.labelsize": 9,
        "axes.spines.top": False,
        "axes.spines.right": False,
        "legend.frameon": False,
    }
)

FIGDIR = os.path.join(os.path.dirname(__file__), "..", "figures")
LOGDIR = os.path.join(os.path.dirname(__file__), "..", "logs")


def savefig(fig, name):
    os.makedirs(FIGDIR, exist_ok=True)
    path = os.path.abspath(os.path.join(FIGDIR, name))
    fig.savefig(path, bbox_inches="tight")
    plt.close(fig)
    print(f"saved {path}")


def _plain(obj):
    """NumPy scalars and arrays as the JSON equivalents, recursively.

    ``json`` refuses ``np.float64`` and ``np.ndarray``, and every number in
    these experiments is one or the other. Converting at the boundary keeps the
    call sites free of ``float(...)`` noise, and keeps the stored numbers full
    precision: rounding here would put the rounding inside the evidence rather
    than inside the README, which is the wrong way round.
    """
    if isinstance(obj, dict):
        return {str(k): _plain(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [_plain(v) for v in obj]
    if isinstance(obj, np.ndarray):
        return _plain(obj.tolist())
    if isinstance(obj, np.generic):
        return _plain(obj.item())
    if isinstance(obj, float) and (np.isnan(obj) or np.isinf(obj)):
        # json writes NaN/Infinity, which is not JSON and not readable by a
        # strict parser. A censored or diverged cell is a real outcome here, so
        # say so in a form that survives a round trip.
        return str(obj)
    return obj


def save_results(name, payload):
    """Write the numbers the README quotes about one experiment to ``logs/``.

    Every figure in this repo is regenerated by ``reproduce.sh`` and checked
    byte-for-byte against the committed copy, so no figure can go stale
    unnoticed. Numbers had no such guard: the README's tables are transcribed
    by hand from a run, and §10's RFF headline (0.088, which was the worst of
    nine feature draws against a median of 0.505) and the same section's "the
    mean is still fine there" were both wrong for a month before a rerun caught
    them. Writing the measurement next to the figure gives
    ``tests/test_readme_numbers.py``
    something to check the prose against, and gives the drift check in
    ``reproduce.sh`` a second class of artifact to notice.

    Keys are sorted and floats are stored at full precision, so a rerun that
    changes nothing produces byte-identical JSON and ``git status`` stays
    quiet.
    """
    os.makedirs(LOGDIR, exist_ok=True)
    path = os.path.abspath(os.path.join(LOGDIR, name + ".json"))
    with open(path, "w") as f:
        json.dump(_plain(payload), f, indent=2, sort_keys=True, allow_nan=False)
        f.write("\n")
    print(f"wrote {path}")
